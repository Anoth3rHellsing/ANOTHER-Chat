import { createInsertSchema } from "drizzle-zod";
import { z } from "zod/v4";
import { messages, messageAttachments, messageReactions, directMessages, dmReadCursors } from "./introspected";
export const messagesTable = messages;
export const messageAttachmentsTable = messageAttachments;
export const messageReactionsTable = messageReactions;
export const directMessagesTable = directMessages;
export const dmReadCursorsTable = dmReadCursors;
export const insertMessageSchema = createInsertSchema(messagesTable).omit({ id: true, editedAt: true, deletedAt: true, createdAt: true });
export type InsertMessage = z.infer<typeof insertMessageSchema>;
export type Message = typeof messagesTable.$inferSelect;
export type MessageAttachment = typeof messageAttachmentsTable.$inferSelect;
export type MessageReaction = typeof messageReactionsTable.$inferSelect;
export type DirectMessage = typeof directMessagesTable.$inferSelect;
export type DmReadCursor = typeof dmReadCursorsTable.$inferSelect;